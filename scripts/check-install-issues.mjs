#!/usr/bin/env node
/**
 * Glitch AI — Install Issues Checker
 *
 * Reads data/install-issues.md, parses any tracked install problems,
 * optionally attempts auto-fixes, and rewrites the file with only
 * unresolved issues remaining.
 *
 * Run:
 *   node scripts/check-install-issues.mjs          # Check and report
 *   node scripts/check-install-issues.mjs --fix   # Check, attempt fix, report
 *
 * Exit codes:
 *   0 = no issues OR all issues resolved
 *   1 = unresolved issues remain (after --fix attempt)
 *
 * Output: JSON to stdout (single line, parseable).
 */

import { existsSync, readFileSync, writeFileSync, unlinkSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// ---------------------------------------------------------------------------
// Setup
// ---------------------------------------------------------------------------

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT_DIR = dirname(__dirname);
const ISSUES_FILE = join(ROOT_DIR, 'data', 'install-issues.md');

const FIX_MODE = process.argv.includes('--fix');

// ---------------------------------------------------------------------------
// Markdown parser
// ---------------------------------------------------------------------------

/**
 * Parse data/install-issues.md into an array of issue objects.
 * Each issue is delimited by a heading like:
 *   ## Install Issue — 2026-07-28
 * followed by bullet fields:
 *   - **Subsystem**: ...
 *   - **Component**: ...
 *   - **Error**: ...
 *   - **Impact**: ...
 *   - **Fix**: ...
 */
function parseIssues(content) {
  const issues = [];
  const blocks = content.split(/^##\s+Install Issue\s*[—–-]\s*/m).slice(1);

  for (const block of blocks) {
    const lines = block.split(/\r?\n/);
    const heading = lines.shift() || '';
    const date = heading.trim();

    const issue = { date };
    for (const line of lines) {
      const m = line.match(/^-\s+\*\*(.+?)\*\*:\s*(.*)$/);
      if (!m) continue;
      const key = m[1].trim().toLowerCase();
      const val = m[2].trim();
      if (key === 'subsystem') issue.subsystem = val;
      else if (key === 'component') issue.component = val;
      else if (key === 'error') issue.error = val;
      else if (key === 'impact') issue.impact = val;
      else if (key === 'fix') issue.fix = val;
    }

    // Only keep blocks that look like real issues (have at least component + error)
    if (issue.component && issue.error) {
      issues.push(issue);
    } else {
      // Log malformed block for debugging
      console.error(`[check-install-issues] Skipping malformed block (date: ${issue.date}, missing: ${!issue.component ? 'component' : 'error'})`);
    }
  }

  return issues;
}

// ---------------------------------------------------------------------------
// Auto-fix
// ---------------------------------------------------------------------------

/**
 * Attempt to auto-fix a single issue based on its subsystem.
 * Returns true if the fix succeeded (issue can be removed).
 */
function attemptFix(issue) {
  const subsystem = (issue.subsystem || '').toLowerCase();

  if (!subsystem.includes('submodule')) return false;

  // Try specific component first
  if (issue.component) {
    try {
      execFileSync('git', ['submodule', 'update', '--init', issue.component], {
        cwd: ROOT_DIR,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
        timeout: 60000,
      });
      // Verify directory exists
      const dir = join(ROOT_DIR, issue.component);
      if (existsSync(dir)) return true;
    } catch { /* fall through to blanket fix */ }
  }

  // Blanket recursive fallback
  try {
    execFileSync('git', ['submodule', 'update', '--init', '--recursive'], {
      cwd: ROOT_DIR,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 60000,
    });
    return true;
  } catch {
    return false;
  }
}

// ---------------------------------------------------------------------------
// File writer
// ---------------------------------------------------------------------------

/**
 * Rewrite install-issues.md with only the unresolved issues.
 * If none remain, delete the file.
 */
function writeRemaining(remaining) {
  if (remaining.length === 0) {
    if (existsSync(ISSUES_FILE)) {
      unlinkSync(ISSUES_FILE);
    }
    return;
  }

  const lines = ['# Install Issues', ''];
  lines.push('Tracked install problems. Auto-generated by `scripts/check-install-issues.mjs`.');
  lines.push('');

  for (const issue of remaining) {
    lines.push(`## Install Issue — ${issue.date || 'unknown'}`);
    if (issue.subsystem) lines.push(`- **Subsystem**: ${issue.subsystem}`);
    if (issue.component) lines.push(`- **Component**: ${issue.component}`);
    if (issue.error) lines.push(`- **Error**: ${issue.error}`);
    if (issue.impact) lines.push(`- **Impact**: ${issue.impact}`);
    if (issue.fix) lines.push(`- **Fix**: ${issue.fix}`);
    lines.push('');
  }

  writeFileSync(ISSUES_FILE, lines.join('\n'), 'utf8');
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function main() {
  // No file → clean state
  if (!existsSync(ISSUES_FILE)) {
    const out = { status: 'no_file', totalIssues: 0, resolvedIssues: 0, remainingIssues: [] };
    console.log(JSON.stringify(out));
    process.exit(0);
  }

  let content;
  try {
    content = readFileSync(ISSUES_FILE, 'utf8');
  } catch (err) {
    const out = {
      status: 'no_file',
      totalIssues: 0,
      resolvedIssues: 0,
      remainingIssues: [],
      error: `read failed: ${err.message}`,
    };
    console.log(JSON.stringify(out));
    process.exit(0);
  }

  const issues = parseIssues(content);

  // Empty file (or only malformed content) → clean
  if (issues.length === 0) {
    if (existsSync(ISSUES_FILE)) {
      try { unlinkSync(ISSUES_FILE); } catch { /* ignore */ }
    }
    const out = { status: 'clean', totalIssues: 0, resolvedIssues: 0, remainingIssues: [] };
    console.log(JSON.stringify(out));
    process.exit(0);
  }

  let resolved = 0;
  const remaining = [];

  for (const issue of issues) {
    if (FIX_MODE) {
      const ok = attemptFix(issue);
      if (ok) {
        resolved += 1;
        continue;
      }
    }
    remaining.push({
      date: issue.date || null,
      subsystem: issue.subsystem || null,
      component: issue.component || null,
      error: issue.error || null,
      impact: issue.impact || null,
      fix: issue.fix || null,
    });
  }

  // Rewrite the file with only unresolved issues
  if (FIX_MODE) {
    writeRemaining(remaining);
  }

  let status;
  if (!FIX_MODE) {
    status = remaining.length === 0 ? 'clean' : 'partial';
  } else if (resolved === issues.length) {
    status = 'fixed';
  } else {
    status = 'partial';
  }

  const out = {
    status,
    totalIssues: issues.length,
    resolvedIssues: FIX_MODE ? resolved : 0,
    remainingIssues: remaining,
  };
  console.log(JSON.stringify(out));

  process.exit(remaining.length === 0 ? 0 : 1);
}

// Export for programmatic use
export { parseIssues, attemptFix, writeRemaining, ISSUES_FILE };

// Run when invoked directly
const isMain = process.argv[1] && (
  fileURLToPath(import.meta.url) === process.argv[1].replace(/\\/g, '/') ||
  process.argv[1].endsWith('check-install-issues.mjs')
);
if (isMain) {
  main();
}
